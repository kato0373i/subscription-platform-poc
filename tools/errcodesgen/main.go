// Command errcodesgen は api/errors.yaml から Go の定数と TS の union 型を生成する（platform.md §7.2）。
// 重複・snake_case でないコード・4xx/5xx 以外の status を見つけたら失敗する。
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
)

type entry struct {
	Code        string `yaml:"code"`
	Status      int    `yaml:"status"`
	Title       string `yaml:"title"`
	Owner       string `yaml:"owner"`
	Description string `yaml:"description"`
}

type file struct {
	Codes []entry `yaml:"codes"`
}

var snake = regexp.MustCompile(`^[a-z][a-z0-9]*(_[a-z0-9]+)*$`)

// Validate は規則を検査する。
func Validate(f file) error {
	var errs []error
	seen := map[string]bool{}
	for _, e := range f.Codes {
		if !snake.MatchString(e.Code) {
			errs = append(errs, fmt.Errorf("code %q is not snake_case", e.Code))
		}
		if seen[e.Code] {
			errs = append(errs, fmt.Errorf("code %q is duplicated", e.Code))
		}
		seen[e.Code] = true
		if e.Status < 400 || e.Status > 599 {
			errs = append(errs, fmt.Errorf("code %q: status %d is not 4xx/5xx", e.Code, e.Status))
		}
		if e.Title == "" || e.Owner == "" {
			errs = append(errs, fmt.Errorf("code %q: title and owner are required", e.Code))
		}
	}
	return errors.Join(errs...)
}

func camel(s string) string {
	var b strings.Builder
	for _, p := range strings.Split(s, "_") {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

// Generate は Go と TS のソースを返す。
func Generate(f file) (goSrc, tsSrc []byte, err error) {
	if err := Validate(f); err != nil {
		return nil, nil, err
	}
	var g bytes.Buffer
	g.WriteString("// Code generated by errcodesgen from api/errors.yaml. DO NOT EDIT.\n\n")
	g.WriteString("// Package errcodes はエラーコードの定数（正本は api/errors.yaml）。\npackage errcodes\n\n")
	g.WriteString("// Code は Problem Details の code。\ntype Code string\n\nconst (\n")
	for _, e := range f.Codes {
		fmt.Fprintf(&g, "\t// %s は %s（%d、owner: %s）。\n\t%s Code = %q\n", camel(e.Code), e.Title, e.Status, e.Owner, camel(e.Code), e.Code)
	}
	g.WriteString(")\n\n// Info はコードの HTTP ステータスと題名。\ntype Info struct {\n\tStatus int\n\tTitle  string\n\tOwner  string\n}\n\n")
	g.WriteString("// All は全コードの情報。\nvar All = map[Code]Info{\n")
	for _, e := range f.Codes {
		fmt.Fprintf(&g, "\t%s: {Status: %d, Title: %q, Owner: %q},\n", camel(e.Code), e.Status, e.Title, e.Owner)
	}
	g.WriteString("}\n\n// Status はコードの HTTP ステータス（未登録なら 500）。\nfunc (c Code) Status() int {\n\tif i, ok := All[c]; ok {\n\t\treturn i.Status\n\t}\n\treturn 500\n}\n\n")
	g.WriteString("// Title はコードの題名。\nfunc (c Code) Title() string { return All[c].Title }\n")
	goSrc, err = format.Source(g.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("format: %w", err)
	}
	var t bytes.Buffer
	t.WriteString("// Code generated by errcodesgen from api/errors.yaml. DO NOT EDIT.\n\nexport type ErrorCode =\n")
	for i, e := range f.Codes {
		sep := ""
		if i == len(f.Codes)-1 {
			sep = ";"
		}
		fmt.Fprintf(&t, "  | %q%s\n", e.Code, sep)
	}
	t.WriteString("\nexport const errorStatus: Record<ErrorCode, number> = {\n")
	for _, e := range f.Codes {
		fmt.Fprintf(&t, "  %s: %d,\n", e.Code, e.Status)
	}
	t.WriteString("};\n")
	return goSrc, t.Bytes(), nil
}

func main() {
	in := flag.String("in", "api/errors.yaml", "入力")
	goOut := flag.String("go", "internal/platform/httpx/errcodes/codes_gen.go", "Go の出力")
	tsOut := flag.String("ts", "web/packages/api-client/src/error-codes.ts", "TS の出力")
	flag.Parse()
	if err := run(*in, *goOut, *tsOut); err != nil {
		fmt.Fprintln(os.Stderr, "errcodesgen:", err) //nolint:forbidigo // CLI の出力
		os.Exit(1)
	}
}

func run(in, goOut, tsOut string) error {
	b, err := os.ReadFile(in) //nolint:gosec // 生成器の入力
	if err != nil {
		return err
	}
	var f file
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(&f); err != nil {
		return fmt.Errorf("parse %s: %w", in, err)
	}
	g, t, err := Generate(f)
	if err != nil {
		return err
	}
	for path, src := range map[string][]byte{goOut: g, tsOut: t} {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil { //nolint:gosec // リポジトリに置く生成物
			return err
		}
		if err := os.WriteFile(path, src, 0o644); err != nil { //nolint:gosec // リポジトリに置く生成物
			return err
		}
	}
	return nil
}
